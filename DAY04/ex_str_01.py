# -----------------------------------------------------------------------
# 파이썬 데이터 종류 - 문자열 str 타입
# - 문자 1개, 문자 여러개 동일 타입 취급
# - ' ', " ", """ """ 안에 데이터 넣기
# - 클래스 정의 => 데이터는 메모리 힙에 저장 => 객체 생성 사용
# -----------------------------------------------------------------------
msg = "Merry Christmas! Happy New Year 2027! "
#                 1         2         3    
#      01234567890123456789012345678901234567
#              3         2         1        -
#      87654321098765432109876543210987654321
# 
print(msg)
print(msg[6:15]) # 6~15: 크리스마스

# => 2027!
print(msg[32:37], msg[32:37]) # 끝 생략 가능
# => Merry
print(msg[0:5], msg[ :5])     # 처음 생략 가능

# => 전부다
print(msg[0:37], msg[ : ])

# ------------------------------------------------------------------------
# 홀수 인덱스만 출력 MryCrsms ap e er22!
# 연속적인 문자 선택 또는 규칙적인 문자 선택 가능
# 변수명[시작인덱스 : 끝인덱스 : 간격]
# 간격 -> 증가방향 2: 2칸씩 띄어쓰기 -1: 거꾸로 읽기
# ------------------------------------------------------------------------
print(msg, msg[ : :2], sep = '\n')
print(msg[ : :-1])

# data = "abc1abc2abc3abc4abc5" 숫자만 출력
#         0         1
#         01234567890123456789
data = "abc1abc2abc3abc4abc5"
print(data[3: :4])
print(data[ : :-1])
