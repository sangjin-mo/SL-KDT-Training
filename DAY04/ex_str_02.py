# 파이썬 데이터 종류 - 문자열 str 타입
# - 관련 내장함수 : len() - 원소 개수 반환
# 원소의 개수 반환 => len
msg = "Merry Christmas! Happy New Year 2027!"
print(f"{msg}의 원소 개수 => {len(msg)}개")

# 기본 데이터 타입 정수 실수 논리 값은 원소 없음
print(f"'123'의 원소 개수 => {len('123')}개")