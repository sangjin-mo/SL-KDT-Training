# -----------------------------------------------------
# 파이썬 내장 함수 : 출력 함수
# 함수 이름 : print()
# 파일에 출력 및 기록
# -----------------------------------------------------
# => 파일 다루기 3단계
# 1단계 : 파일 열기 : open(파일명, 모드) : 파일 열기 함수 - 내장함수 -> 파일객체
# 2단계 : 파일 작업 : 파일객체명.r(읽기), w(쓰기), a(추가)         - 메서드 -> 파일 전용 함수
# 3단계 : 파일 닫기 : 파일객체명.close() : 파일 닫기 함수          - 메서드 -> 파일 전용 함수
# -----------------------------------------------------
# 파일 생성---------------------
# 파일명 저장 , 전부 대문자로 상수 처리
FILE_NAME = "test.txt" 
# 1단계 : 파일 열기     
myfile = open(FILE_NAME, mode = "w")
# 2단계 : 파일 작업
myfile.write("good luck 2027!\n") # 파일에 기록
myfile.write("Happy 2027!") # 파일에 기록
# 3단계 : 파일 닫기
myfile.close()
# -----------------------------------------------------
# => print) 결과를 파일에 쓰기
# -----------------------------------------------------
FILE_NAME = "log.txt"
# 1단계 : 파일 열기     
logfile = open(FILE_NAME, mode = "w")
# 2단계 : 파일 작업 => print()
print(1+2+3+4+5, file = logfile) # 파일에 기록
# 3단계 : 파일 닫기
logfile.close()