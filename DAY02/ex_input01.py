# -----------------------------------------------------
# 파이썬 내장 함수 : 입력 함수
# 함수 이름 : input()
# 특징 : 요청하는 데이터를 키보드로부터 전달받을 수 있는 함수
#       Enter를 누르기 전까지 대기
#       입력받은 데이터는 모두 문자열로 반환
# -----------------------------------------------------
# => 1)이름 2)나이 입력 받기
name = input("이름을 입력하세요 : ")
age = input("나이를 입력하세요 : ")

# 입력받은 데이터 출력
print(f"입력받은 데이터 => 이름: {name}, 나이: {age}")

# => 숫자 2개 입력 받기
first = input("숫자 1 입력 : ") # => 입력 받은 데이터는 문자열로 반환 '7'
second = input("숫자 2 입력 : ") # => 입력 받은 데이터는 문자열로 반환 '3'

# 입력받은 데이터는 모두 문자열로 반환되므로 숫자 연산을 위해서는 형변환 필요
print(f"입력받은 숫자 더하기 => {first} + {second} = {first + second}") 
print(f"입력받은 숫자 더하기 => int({first}) + int({second}) = {int(first) + int(second)}") 