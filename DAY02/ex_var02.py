# -----------------------------------------
# 파이썬 변수 저장 데이터 확인
# 참조변수 : 힙에 저장된 데이터 주소를 저장하는 변수
# 변수: 실제 데이터를 저장하는 변수 <- 파이썬은 전부 힙에 저장하므로 없음
# -----------------------------------------
# 내장함수 : id(변수명 or 데이터) : 참조변수의 저장된 주소를 확인하는 함수
# -----------------------------------------
# 실습조건 : 동일한 데이터를 다른 변수에 저장하기

# 변수 산안
value = 3
age   = 3

# 변수가 저장한 값 확인 및 출력
# 동일한 데이터는 힙 메모리에 1개만 저장, 그 주소를 변수들에게 전달 => 참조 카운트 증가
print("id(value) =>", id(value))  # 참조변수 value에 저장된 주소 확인
print("id(age)   =>", id(age))    # 참조변수 age에 저장된 주소 확인

# 변수 값 변경 : 변수명 = 새로운 값
age   = 100
print("id(value) =>", id(value))  # 참조변수 value에 저장된 주소 확인
print("id(age)   =>", id(age))    # 참조변수 age에 저장된 주소 확인 
