# -----------------------------------------
# 파이썬 내장 함수 : 출력 함수
# 함수 이름 : print()
# 특징 : [] 출력시 자동 줄 바꿈 문자 추가
#          여러개 데이터에 공백 문자 추가
# => [기본동작]

name = '홍길동'

print(name)             # '홍길동\n' 출력
print('홍길동')          # '홍길동\n' 출력
print(2027)             # '2027\n' 출력

print(name, '홍길동', 2027)  # '홍길동 홍길동 2027\n' 출력

# => [기본값 변경 - 분리자sep]
print(name, '홍길동', 2027, sep='*')  # '홍길동*홍길동*2027\n' 출력
print(name, '홍길동', 2027, sep='^')  # '홍길동^홍길동^2027\n' 출력 
print(name, '홍길동', 2027, sep='&')  # '홍길동&홍길동&2027\n' 출력
print(name, '홍길동', 2027, sep='')  # '홍길동홍길동2027\n' 출력

# => [기본값 변경 - 종료 문자end]
print(name, '홍길동', 2027, sep='*', end='★')  # '홍길동*홍길동*2027!' 출력
print("새로운 메시지") # '새로운 메시지\n' 출력