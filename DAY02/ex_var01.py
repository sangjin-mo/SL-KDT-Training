# -----------------------------------------
# 파이썬 변수 저장 데이터 확인
# 참조변수 : 힙에 저장된 데이터 주소를 저장하는 변수
# 변수: 실제 데이터를 저장하는 변수 <- 파이썬은 전부 힙에 저장하므로 없음
# -----------------------------------------
# 내장함수 : id(변수명 or 데이터) : 참조변수의 저장된 주소를 확인하는 함수
# -----------------------------------------
# 데이터 11을 heap memory에 저장하고, 참조변수 month에 해당 주소를 저장
month = 11

# 출력 확인
print("id(month) =>", id(month))  # 참조변수 month에 저장된 주소 확인
print("id(11)    =>", id(11))       # 데이터 11이 저장된 주소 확인
print("month     =>", month)         # 참조변수 month에 저장된 데이터 확인