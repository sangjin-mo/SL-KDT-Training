# -----------------------------------------------------------------
# 문자열 자료형 ('' / " " / """ """)
# 구성 => 여러개의 문자들로 구성
# 문자열 전용 메서드 많음 => 많이 알수록 편함
# ------------------------------------------------------------------ 
# 인덱싱 : 문자열 내 문자들을 식별하는 방법
# 왼쪽 -> 오른쪽 :  0 ~ 인덱스
# 오른쪽 -> 왼쪽 : -1 ~ 인덱스
# ------------------------------------------------------------------
msg = "good luck"
#      012345678
#              -
#      987654321
# -------------------------------------------------------------------
print(f'msg => 전체 문자열 : {msg}')   
print(f'msg => 특정한 문자 : {msg[0]}, {msg[-9]}') 
# ------------------------------------------------------------------
# 슬라이싱 : (시작) ~ (끝 - 1) >> 문자열 내 지정된 범위의 요소들 가져오기
# 변수명 [시작인덱스 : 끝인덱스] -> 마지막 출력 문자 + 1 까지 설정할것
# 시작인덱스 <= value < 끝인덱스
# ------------------------------------------------------------------
# 'good' 출력하려면? [0123]
print(f'good => {msg[0:3]} / {msg[0:4]}')
# 0<= ~ <3 , 0<= ~ <4  마지막 문자 주의